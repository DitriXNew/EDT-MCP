package com.ditrix.edt.mcp.server.tools;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.junit.After;
import org.junit.Before;
import org.junit.Test;

import com.ditrix.edt.mcp.server.utils.GuideLoader;
import com.ditrix.edt.mcp.server.utils.GuideRenderer;

/**
 * Keeps checked-in tool pages in step with the complete production registry,
 * including tools hidden from tools/list. Description, schema and guide changes
 * must regenerate their pages in the same change.
 */
public class ToolDocsRatchetTest
{
    // Deliberately duplicated from FOOTER in docs/generate_tool_docs.py.
    // Keep both copies identical: this footer is part of the generated-page contract.
    private static final String FOOTER = "\n\n---\n*Generated from the live MCP server "
        + "(`get_tool_guide`) by `docs/generate_tool_docs.py`. "
        + "Do not edit this file. Edit the tool's description/schema in its Java "
        + "source and its guide body in "
        + "`mcp/bundles/com.ditrix.edt.mcp.server/guides/<tool>.md`.*\n";

    private static final String REGENERATE = "Tool documentation is stale. Every description, schema or guide "
        + "change must regenerate its page in the same PR. Run python docs/generate_tool_docs.py --port <port> "
        + "against a server running this build. If the page contains [OUTPUT TRUNCATED], the generator fell "
        + "back to tools/call; use a server supporting resources/read guide://<toolName>.";

    private static final String INDEX_START = "<!-- TOOLS-INDEX:START -->";
    private static final String INDEX_END = "<!-- TOOLS-INDEX:END -->";
    // The folder index puts its period inside the bold count; the root index does not.
    private static final Pattern TOOL_COUNT = Pattern.compile("^\\*\\*(\\d+) tools\\.?\\*\\*", Pattern.MULTILINE);

    private McpToolRegistry registry;
    private Path root;

    @Before
    public void setUp()
    {
        registry = McpToolRegistry.getInstance();
        BuiltInToolRegistrar.registerAll(registry);
        GuideLoader.clearCache();
        assertFalse("The production registry must not be empty", registry.getAllTools().isEmpty());
        root = locateRepoRoot();
        assertNotNull("Could not locate the repository from user.dir=" + System.getProperty("user.dir"), root);
    }

    @After
    public void tearDown()
    {
        registry.clear();
        GuideLoader.clearCache();
    }

    @Test
    public void everyRegisteredToolPageIsCurrent() throws IOException
    {
        List<String> mismatches = new ArrayList<>();
        for (String name : registeredNames())
        {
            Path page = root.resolve("docs/tools/" + name + ".md");
            if (!Files.isRegularFile(page))
            {
                mismatches.add("docs/tools/" + name + ".md: missing page");
                continue;
            }
            String expected = pageText(registry.getTool(name));
            String actual = normalizeLf(Files.readString(page, StandardCharsets.UTF_8));
            if (!expected.equals(actual))
            {
                mismatches.add("docs/tools/" + name + ".md: " + firstDifferentLine(expected, actual));
            }
        }
        assertEquals(REGENERATE + "\n" + String.join("\n", mismatches), 0, mismatches.size());
    }

    @Test
    public void everyPageNamesARegisteredTool() throws IOException
    {
        Set<String> names = registeredNames();
        List<String> stalePages = new ArrayList<>();
        try (DirectoryStream<Path> pages = Files.newDirectoryStream(root.resolve("docs/tools"), "*.md"))
        {
            for (Path page : pages)
            {
                String filename = page.getFileName().toString();
                if (!filename.equals("README.md") && !names.contains(filename.substring(0, filename.length() - 3)))
                {
                    stalePages.add("docs/tools/" + filename);
                }
            }
        }
        Collections.sort(stalePages);
        assertEquals("Pages for removed, renamed or unregistered tools: " + stalePages
            + ". Remove obsolete pages. " + REGENERATE, 0, stalePages.size());
    }

    @Test
    public void indexLinksEveryRegisteredToolWithTheRightCount() throws IOException
    {
        List<String> problems = new ArrayList<>();
        checkIndex("docs/tools/README.md", Files.readString(root.resolve("docs/tools/README.md"),
            StandardCharsets.UTF_8), "", problems);

        String readme = normalizeLf(Files.readString(root.resolve("README.md"), StandardCharsets.UTF_8));
        int start = readme.indexOf(INDEX_START);
        int end = readme.indexOf(INDEX_END);
        if (start < 0 || end <= start)
        {
            problems.add("README.md: missing or misordered TOOLS-INDEX markers");
        }
        else
        {
            checkIndex("README.md TOOLS-INDEX", readme.substring(start + INDEX_START.length(), end),
                "docs/tools/", problems);
        }
        assertEquals(REGENERATE + "\n" + String.join("\n", problems), 0, problems.size());
    }

    @Test
    public void pageAssemblyNormalizesLineEndingsAndTrailingBlankLines()
    {
        IMcpTool tool = new IMcpTool()
        {
            @Override
            public String getName()
            {
                return "normalization_stub";
            }

            @Override
            public String getDescription()
            {
                return "A stub description.";
            }

            @Override
            public String getInputSchema()
            {
                return "{}";
            }

            @Override
            public String getGuide()
            {
                return "First line.\r\nSecond line.\rThird line.\r\n \t\r\n\r\n";
            }

            @Override
            public String execute(Map<String, String> params)
            {
                throw new UnsupportedOperationException("Documentation must not execute tools");
            }
        };

        assertEquals("# normalization_stub\n\nA stub description.\n\n## Parameters\nNo parameters.\n"
            + "\n## Guide\nFirst line.\nSecond line.\nThird line." + FOOTER, pageText(tool));
    }

    private Set<String> registeredNames()
    {
        Set<String> names = new TreeSet<>();
        for (IMcpTool tool : registry.getAllTools())
        {
            names.add(tool.getName());
        }
        return names;
    }

    private void checkIndex(String label, String text, String prefix, List<String> problems)
    {
        Set<String> names = registeredNames();
        Matcher count = TOOL_COUNT.matcher(normalizeLf(text));
        if (!count.find() || !count.group(1).equals(Integer.toString(names.size())))
        {
            problems.add(label + ": expected a bold count of " + names.size() + " tools");
        }
        for (String name : names)
        {
            if (!text.contains("](" + prefix + name + ".md)"))
            {
                problems.add(label + ": missing link to " + prefix + name + ".md");
            }
        }
        // A renamed or removed tool must not leave its row behind, even when the count still matches.
        Matcher link = Pattern.compile("\\]\\(" + Pattern.quote(prefix) + "([A-Za-z0-9_]+)\\.md\\)") //$NON-NLS-1$ //$NON-NLS-2$
            .matcher(text);
        while (link.find())
        {
            String linked = link.group(1);
            if (!"README".equals(linked) && !names.contains(linked)) //$NON-NLS-1$
            {
                problems.add(label + ": links to " + prefix + linked + ".md, which is not a registered tool");
            }
        }
    }

    @Test
    public void indexRejectsALinkToAToolThatIsNoLongerRegistered()
    {
        StringBuilder index = new StringBuilder("**" + registeredNames().size() + " tools.**\n"); //$NON-NLS-1$ //$NON-NLS-2$
        for (String name : registeredNames())
        {
            index.append("| [`").append(name).append("`](").append(name).append(".md) | x |\n"); //$NON-NLS-1$ //$NON-NLS-2$ //$NON-NLS-3$ //$NON-NLS-4$
        }
        List<String> clean = new ArrayList<>();
        checkIndex("index", index.toString(), "", clean); //$NON-NLS-1$ //$NON-NLS-2$
        assertEquals(clean.toString(), 0, clean.size());
        index.append("| [`removed_tool`](removed_tool.md) | stale |\n"); //$NON-NLS-1$
        List<String> stale = new ArrayList<>();
        checkIndex("index", index.toString(), "", stale); //$NON-NLS-1$ //$NON-NLS-2$
        assertEquals(stale.toString(), 1, stale.size());
    }

    private static String pageText(IMcpTool tool)
    {
        return normalizeLf(GuideRenderer.render(tool)).stripTrailing() + FOOTER;
    }

    private static String normalizeLf(String text)
    {
        return text.replace("\r\n", "\n").replace('\r', '\n');
    }

    private static String firstDifferentLine(String expected, String actual)
    {
        String[] expectedLines = expected.split("\n", -1);
        String[] actualLines = actual.split("\n", -1);
        for (int i = 0; i < Math.max(expectedLines.length, actualLines.length); i++)
        {
            String expectedLine = i < expectedLines.length ? expectedLines[i] : "<end of file>";
            String actualLine = i < actualLines.length ? actualLines[i] : "<end of file>";
            if (i >= expectedLines.length || i >= actualLines.length || !expectedLine.equals(actualLine))
            {
                return "line " + (i + 1) + ": expected " + summarizeLine(expectedLine)
                    + " but was " + summarizeLine(actualLine);
            }
        }
        throw new IllegalArgumentException("Expected different page text");
    }

    private static String summarizeLine(String line)
    {
        String excerpt = line.length() > 160 ? line.substring(0, 157) + "..." : line;
        return "\"" + excerpt.replace("\t", "\\t") + "\" (" + line.length() + " chars)";
    }

    // Keep this locator private: other ratchets have their own independent root discovery.
    private static Path locateRepoRoot()
    {
        Path dir = Path.of(System.getProperty("user.dir")).toAbsolutePath();
        for (int i = 0; i < 12 && dir != null; i++, dir = dir.getParent())
        {
            if (Files.isRegularFile(dir.resolve("docs/generate_tool_docs.py"))
                && Files.isDirectory(dir.resolve("mcp")))
            {
                return dir;
            }
        }
        return null;
    }
}
